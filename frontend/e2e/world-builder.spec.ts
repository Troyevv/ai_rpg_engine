test('field proposals require preview acceptance and preserve neighbours',async({page,request})=>{
 const w=await (await request.post('/api/workspaces',{data:{name:'ИИ-предложения'}})).json();
 await request.post(`/api/workspaces/${w.id}/builder`,{data:{revision:w.revision}});
 await page.addInitScript(id=>localStorage.setItem('builderWorkspace',id),w.id);
 await page.goto('/');await nav(page,'Создать');await page.getByRole('button',{name:'Создание мира вручную',exact:true}).click();
 const section=async(name:string)=>page.getByRole('navigation',{name:'Разделы конструктора'}).getByRole('button',{name,exact:true}).click();
 await section('Стартовая сцена');await page.getByLabel('Ситуация',{exact:true}).fill('Старая сцена');
 await page.getByRole('button',{name:'Сохранить черновик',exact:true}).click();
 await expect(page.locator('.builder-toolbar').getByRole('status')).toHaveText('Изменения сохранены');
 const original=await (await request.get(`/api/workspaces/${w.id}/builder`)).json();
 const generate=async()=>{
  await page.getByLabel('Ситуация',{exact:true}).locator('..').getByRole('button',{name:'✦ Предложить текст',exact:true}).click();
  await page.getByLabel('Указание генератору').fill('Сделай сцену спокойной');
  await page.getByRole('button',{name:'Сгенерировать предложение',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Принять предложенное изменение?'})).toBeVisible();
 };
 await generate();await page.getByRole('button',{name:'Отклонить',exact:true}).click();
 expect((await (await request.get(`/api/workspaces/${w.id}/builder`)).json()).state).toEqual(original.state);
 await generate();await page.getByRole('button',{name:'Принять в черновик',exact:true}).click();
 await expect(page.getByLabel('Ситуация',{exact:true})).toHaveValue(/Спокойный/);
 expect((await (await request.get(`/api/workspaces/${w.id}/builder`)).json()).revision).toBe(original.revision);
 await page.getByRole('button',{name:'Сохранить черновик',exact:true}).click();
 await expect(page.locator('.builder-toolbar').getByRole('status')).toHaveText('Изменения сохранены');
 const after=await (await request.get(`/api/workspaces/${w.id}/builder`)).json();
 expect(after.state.world_state.meta).toEqual(original.state.world_state.meta);
 expect(after.state.world_state.camera.situation).not.toBe(original.state.world_state.camera.situation);
});

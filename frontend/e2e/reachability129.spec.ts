import { test, expect } from '@playwright/test';
import {defaults} from '../src/types';

test('all recipients: no contact, keyboard, send once, history and unanswered call', async ({page, request}, info) => {
  const workspace=await (await request.post('/api/workspaces',{data:{name:'Contact-free generation'}})).json();
  const url=`/api/workspaces/${workspace.id}/draft`;
  const generated=await request.post(url+'/generate',{data:{revision:0,text:'TEST_CONTACT_FREE_WORLD: современный город, сообщения и звонки.',config:defaults.game}});
  expect(generated.ok()).toBeTruthy();
  const jid=(await generated.json()).id;
  await expect.poll(async()=> (await (await request.get('/api/jobs/'+jid)).json()).status,{timeout:60000}).toBe('saved');
  const draft=await (await request.get(url+'?author=true')).json();
  expect(draft.state.world.contacts).toEqual({});
  const confirmed=await request.post(url+'/confirm',{data:{revision:draft.revision,version_id:draft.version_id,accept_warnings:true}});
  expect(confirmed.ok()).toBeTruthy();
  const selected=await confirmed.json();
  await page.addInitScript(s=>localStorage.setItem('selection',JSON.stringify(s)),selected);
  await request.put(`/api/worlds/${selected.world}/presentation`,{data:{theme_id:'graphite'}});
  await page.goto('/');
  await page.getByRole('button',{name:'Начать игру',exact:true}).click();
  await expect(page.getByLabel('Своё действие или реплика')).toBeEnabled();
  const initial = await (await request.get(`/api/saves/${selected.save}`)).json();
  expect(initial.state.phone.contacts).toHaveLength(0);
  const recipient = initial.state.phone.recipients[0];
  expect(recipient.can_send && recipient.can_call).toBeTruthy();
  await page.getByRole('button',{name:/^Телефон/}).click();
  const phone=page.getByRole('region',{name:'Телефон персонажа'});
  await phone.getByLabel('Поиск адресата').fill(recipient.subject.name);
  const row=phone.locator('.phone-recipient').filter({hasText:recipient.subject.name});
  await expect(row).toHaveCount(1);
  const actionBounds = await row.getByRole('button',{name:/Написать:/}).boundingBox();
  expect(actionBounds!.width).toBeGreaterThanOrEqual(44);
  expect(actionBounds!.height).toBeLessThan(80);
  await expect(row.getByRole('button',{name:/Написать:/})).toBeEnabled();
  if(process.env.REACHABILITY_QA) await page.screenshot({path:`/tmp/reachability129-${info.project.name}-graphite.png`});
  await row.getByRole('button',{name:/Написать:/}).focus();
  await page.keyboard.press('Enter');
  await phone.getByLabel('Сообщение в телефоне').fill('Первое обращение без контакта.');
  await phone.getByRole('button',{name:'Отправить сообщение',exact:true}).dblclick();
  await expect(phone.getByText('Первое обращение без контакта.',{exact:true})).toBeVisible();
  await expect(phone.getByRole('button',{name:/Подождать ещё/})).toBeEnabled();
  const sent=await (await request.get(`/api/saves/${selected.save}`)).json();
  expect(sent.state.phone.contacts).toHaveLength(0);
  expect(sent.state.phone.events.filter((e:any)=>e.outgoing&&e.channel==='TEXT_MESSAGE')).toHaveLength(1);
  await page.reload();
  await page.getByRole('button',{name:/^Телефон/}).click();
  await phone.getByRole('button',{name:'Переписки',exact:true}).click();
  await phone.getByRole('button').filter({hasText:recipient.subject.name}).click();
  await expect(phone.getByText('Первое обращение без контакта.',{exact:true})).toBeVisible();
  await phone.getByRole('button',{name:'Контакты',exact:true}).click();
  await phone.getByLabel('Поиск адресата').fill(recipient.subject.name);
  await row.getByRole('button',{name:/Позвонить:/}).click();
  await expect(phone.getByText(/Исходящий · Пропущен/)).toBeVisible();
  await page.reload();
  const reloaded=await (await request.get(`/api/saves/${selected.save}`)).json();
  expect(reloaded.state.phone.contacts).toHaveLength(0);
  expect(reloaded.state.phone.events).toHaveLength(2);
  expect(reloaded.state.phone.events.find((e:any)=>e.channel==='VOICE_CALL').status).toBe('missed');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
});

test('directory search, localization and two skins at large text size', async ({page,request}, info)=>{
  const selected=await (await request.post('/test/phone-seed?incoming=false&strangers=true')).json();
  await page.addInitScript(s=>{localStorage.setItem('selection',JSON.stringify(s));},selected);
  await request.put(`/api/worlds/${selected.world}/presentation`,{data:{theme_id:'parchment'}});
  await page.goto('/');
  await page.getByRole('button',{name:/^Телефон/}).click();
  const phone=page.getByRole('region',{name:'Телефон персонажа'});
  if(process.env.REACHABILITY_QA) await page.screenshot({path:`/tmp/reachability129-${info.project.name}-parchment.png`});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.evaluate(()=>{document.documentElement.style.fontSize='200%';});
  await phone.getByLabel('Поиск адресата').fill('несуществующее имя');
  await expect(phone.getByRole('status')).toHaveText('Адресаты не найдены.');
  await phone.getByLabel('Поиск адресата').fill('');
  await expect(phone.locator('.phone-recipient').first()).toBeVisible();
  const largeTextAction = phone.locator('.phone-recipient').first().getByRole('button').first();
  await largeTextAction.scrollIntoViewIfNeeded();
  expect((await largeTextAction.boundingBox())!.width).toBeGreaterThanOrEqual(44);
  if(process.env.REACHABILITY_QA) await page.screenshot({path:`/tmp/reachability129-${info.project.name}-large-text.png`,animations:'disabled'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await page.evaluate(()=>{document.documentElement.lang='en';});
  await phone.getByLabel('Поиск адресата').fill('zzzz');
  await expect(phone.getByRole('region',{name:'Recipients'})).toBeVisible();
  await expect(phone.getByRole('status')).toHaveText('No recipients found.');
  await page.keyboard.press('Escape');
  await expect(phone).toHaveCount(0);
});

test('saved labels share the directory with unsaved NPCs and remain editable', async ({page,request})=>{
  const selected=await (await request.post('/test/phone-seed?incoming=false')).json();
  await page.addInitScript(s=>localStorage.setItem('selection',JSON.stringify(s)),selected);
  await page.goto('/');
  await page.getByRole('button',{name:/^Телефон/}).click();
  const phone=page.getByRole('region',{name:'Телефон персонажа'});
  await expect(phone.getByRole('button',{name:'Добавить контакт',exact:true})).toHaveCount(0);
  await expect(phone.locator('.phone-directory-tabs')).toHaveCount(0);
  await phone.getByLabel('Поиск адресата').fill('Вера');
  await phone.getByRole('button',{name:'Вера работа',exact:true}).click();
  await phone.getByText('Управление контактом',{exact:true}).click();
  await phone.getByRole('button',{name:'Переименовать',exact:true}).click();
  await phone.getByLabel('Сохранённое имя').fill('Коллега');
  await phone.getByRole('button',{name:'Сохранить контакт',exact:true}).click();
  await expect(phone.getByRole('button',{name:'Коллега',exact:true})).toBeVisible();
  await phone.getByRole('button',{name:'Назад',exact:true}).click();
  // Canonical name still finds an arbitrarily renamed saved label.
  await phone.getByLabel('Поиск адресата').fill('Вера');
  await expect(phone.getByRole('button',{name:'Коллега',exact:true})).toBeVisible();
  await phone.getByLabel('Поиск адресата').fill('Коллега');
  await expect(phone.locator('.phone-recipient')).toHaveCount(1);
  await page.reload();
  await page.getByRole('button',{name:/^Телефон/}).click();
  await expect(phone.getByRole('button',{name:'Коллега',exact:true})).toBeVisible();
});

import { test, expect } from '@playwright/test';

test('all recipients: no contact, keyboard, send once, history and unanswered call', async ({page, request}, info) => {
  const selected = await (await request.post('/test/phone-seed?incoming=false&strangers=true')).json();
  await page.addInitScript(s=>localStorage.setItem('selection',JSON.stringify(s)),selected);
  const initial = await (await request.get(`/api/saves/${selected.save}`)).json();
  expect(initial.state.phone.contacts).toHaveLength(0);
  const recipient = initial.state.phone.recipients.find((r:any)=>r.id==='qa_vera');
  expect(recipient.can_send && recipient.can_call).toBeTruthy();
  await request.put(`/api/worlds/${selected.world}/presentation`,{data:{theme_id:'graphite'}});
  await page.goto('/');
  await page.getByRole('button',{name:/^Телефон/}).click();
  const phone=page.getByRole('region',{name:'Телефон персонажа'});
  const directory=phone.getByRole('button',{name:/Все персонажи/});
  await directory.focus(); await page.keyboard.press('Enter');
  await phone.getByLabel('Поиск адресата').fill(recipient.subject.name);
  const row=phone.locator('.phone-recipient').filter({hasText:recipient.subject.name});
  await expect(row).toHaveCount(1);
  const actionBounds = await row.getByRole('button',{name:/Написать:/}).boundingBox();
  expect(actionBounds!.width).toBeGreaterThan(100);
  expect(actionBounds!.height).toBeLessThan(80);
  if(process.env.REACHABILITY_QA) await page.screenshot({path:`/tmp/reachability129-${info.project.name}-graphite.png`});
  await row.getByRole('button',{name:/Написать:/}).click();
  await phone.getByLabel('Сообщение в телефоне').fill('Первое обращение без контакта.');
  await phone.getByRole('button',{name:'Отправить сообщение',exact:true}).dblclick();
  await expect(phone.getByText('Первое обращение без контакта.',{exact:true})).toBeVisible();
  await expect(phone.getByRole('button',{name:/Подождать ещё/})).toBeEnabled();
  const sent=await (await request.get(`/api/saves/${selected.save}`)).json();
  expect(sent.state.phone.contacts).toHaveLength(0);
  expect(sent.state.phone.events.filter((e:any)=>e.outgoing&&e.channel==='TEXT_MESSAGE')).toHaveLength(1);
  await page.reload();
  await page.getByRole('button',{name:/^Телефон/}).click();
  await phone.getByRole('button',{name:'Переписки',exact:true}).click();
  await phone.getByRole('button').filter({hasText:recipient.subject.name}).click();
  await expect(phone.getByText('Первое обращение без контакта.',{exact:true})).toBeVisible();
  await phone.getByRole('button',{name:'Контакты',exact:true}).click();
  await phone.getByRole('button',{name:/Все персонажи/}).click();
  await phone.getByLabel('Поиск адресата').fill(recipient.subject.name);
  await row.getByRole('button',{name:/Позвонить:/}).click();
  await expect(phone.getByText(/Исходящий · Пропущен/)).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
});

test('directory search, localization and two skins at large text size', async ({page,request}, info)=>{
  const selected=await (await request.post('/test/phone-seed?incoming=false&strangers=true')).json();
  await page.addInitScript(s=>{localStorage.setItem('selection',JSON.stringify(s));},selected);
  await request.put(`/api/worlds/${selected.world}/presentation`,{data:{theme_id:'parchment'}});
  await page.goto('/');
  await page.getByRole('button',{name:/^Телефон/}).click();
  const phone=page.getByRole('region',{name:'Телефон персонажа'});
  await phone.getByRole('button',{name:/Все персонажи/}).click();
  if(process.env.REACHABILITY_QA) await page.screenshot({path:`/tmp/reachability129-${info.project.name}-parchment.png`});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.evaluate(()=>{document.documentElement.style.fontSize='200%';});
  await phone.getByLabel('Поиск адресата').fill('несуществующее имя');
  await expect(phone.getByRole('status')).toHaveText('Адресаты не найдены.');
  await phone.getByLabel('Поиск адресата').fill('');
  await expect(phone.locator('.phone-recipient').first()).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await page.evaluate(()=>{document.documentElement.lang='en';});
  await phone.getByLabel('Поиск адресата').fill('zzzz');
  await expect(phone.getByRole('button',{name:/All characters/})).toBeVisible();
  await expect(phone.getByRole('status')).toHaveText('No recipients found.');
  await page.keyboard.press('Escape');
  await expect(phone).toHaveCount(0);
});

import {test,expect} from '@playwright/test';
import {mkdirSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
for(const theme of ['graphite','parchment'])test(`one world during and after NPC hangup: ${theme}`,async({page,request},info)=>{
 test.setTimeout(120000);
 if(info.project.name==='mobile')await page.setViewportSize({width:theme==='graphite'?360:393,height:800});
 await page.emulateMedia({reducedMotion:'reduce'});
 const seed=await(await request.post('/test/phone-seed?incoming=false&decision=office')).json();
 expect(seed.save).toBeTruthy();
 await request.put(`/api/worlds/${seed.world}/presentation`,{data:{theme_id:theme}});
 await page.addInitScript(s=>localStorage.setItem('selection',JSON.stringify(s)),seed);await page.goto('/');
 const state=async()=>await(await request.get(`/api/saves/${seed.save}`)).json();
 const capture=async(name:string)=>{const dir=process.env.CALL_CONTINUITY_EVIDENCE;if(!dir)return;mkdirSync(dir,{recursive:true});await page.screenshot({path:join(dir,`${info.project.name}-${theme}-${name}.png`),animations:'disabled'});writeFileSync(join(dir,`${info.project.name}-${theme}-${name}.json`),JSON.stringify(await state(),null,2))};
 const story=page.locator('.story-scroll');const input=page.getByLabel('Своё действие или реплика');
 await expect(story).toContainText('пока не стучит');await expect(page.locator('.choices')).toContainText('Посмотреть на часы');
 await input.fill('Черновик физического действия');await capture('before');
 await page.getByRole('button',{name:/^Телефон/}).click();const phone=page.getByRole('region',{name:'Телефон персонажа'});
 await phone.getByRole('button',{name:'Катя',exact:true}).click();await phone.getByRole('button',{name:'Позвонить',exact:true}).click();
 const call=page.getByRole('dialog',{name:'Сцена звонка'});await expect(call).toBeVisible();
 const before=await state();const start=before.state.world_clock.minute;
 const speech=async(text:string)=>{await call.getByLabel('Реплика в звонке').fill(text);await call.getByLabel('Сказать собеседнику').click()};
 await speech('Встретимся через час?');
 // Streaming is provisional: physical history receives only accepted projections.
 await expect(call).toContainText('Катя отвечает');
 await expect.poll(async()=>(await state()).job.status).toBe('saved');
 await expect(story).toContainText('Виктория трижды стучит');
 await expect(story).not.toContainText('Да, договорились');
 await expect(page.locator('.choices')).toContainText('ответить Виктории');
 await expect(call).not.toContainText('Виктория трижды стучит');await capture('during-call');
 await call.getByLabel('Свернуть звонок').click();await expect(input).toHaveValue('Черновик физического действия');await capture('during-physical');
 await page.getByRole('button',{name:/Вернуться к звонку/}).click();await speech('Я скоро освобожусь.');
 await expect.poll(async()=>(await state()).job.status).toBe('saved');
 await expect(story).toContainText('мне нужен ответ');
 expect((await state()).state.phone.events.find((e:any)=>e.channel==='VOICE_CALL').status).toBe('answered');
 await speech('Тогда до встречи.');await expect(call).toHaveCount(0);
 await expect(input).toBeEnabled();await expect(input).toHaveValue('Черновик физического действия');
 await expect(page.locator('.choices')).toContainText('ответить Виктории');
 await expect(page.locator('.choices')).not.toContainText('Посмотреть на часы');
 const after=await state();expect(after.state.world_clock.minute).toBe(start+6);
 expect(after.state.phone.events.find((e:any)=>e.channel==='VOICE_CALL').status).toBe('ended');
 expect(after.state.world.scheduled_events['office-meeting'].time_reference_minute).toBe(start);
 const date=after.state.world_clock.projection.date;
 const calendar=await(await request.get(`/api/saves/${seed.save}/calendar?start_date=${date}&end_date=${date}`)).json();expect(JSON.stringify(calendar)).toContain('office-meeting');
 const cards=await story.locator('.turn').allTextContents();expect(cards.findIndex(t=>t.includes('трижды стучит'))).toBeLessThan(cards.findIndex(t=>t.includes('мне нужен ответ')));
 await capture('after');await page.reload();await expect(story).toContainText('мне нужен ответ');await expect(page.locator('.choices')).toContainText('ответить Виктории');
 // Reopening an ended call is read-only and cannot replay consequences.
 await page.getByRole('button',{name:/^Телефон/}).click();
 await phone.getByRole('button',{name:'Звонки',exact:true}).click();
 await phone.getByRole('button',{name:'Читать разговор',exact:true}).click();
 await expect(call).toBeVisible();await expect(call).toContainText('щёлкает отбой');
 await expect(call.getByLabel('Реплика в звонке')).toHaveCount(0);
 expect((await state()).state.world_clock.minute).toBe(start+6);
 await call.getByRole('button',{name:'Закрыть разговор',exact:true}).click();
 await input.fill('Ответить Виктории.');await page.getByRole('button',{name:'Отправить действие',exact:true}).click();
 await expect(story).toContainText('После её стука и требования ответа');await expect(input).toBeEnabled();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});

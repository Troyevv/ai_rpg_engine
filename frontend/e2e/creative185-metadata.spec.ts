import {confirmWorkshopStart} from './workshop-navigation';
import {workshopNav} from './workshop-navigation';
import {test,expect} from '@playwright/test';
import {nav} from './navigation';
test('optional creative rejection preserves the reviewed base and allows play without regeneration',async({page,request})=>{
 const response=await request.post('/test/creative185-rejected');expect(response.ok(),await response.text()).toBe(true);
 const workspace=await response.json();const url=`/api/workspaces/${workspace.id}/draft`;
 const before=await(await request.get(url+'?author=true')).json();
 const raw=await(await request.get(url+'/raw')).json();
 expect(raw.creative.status).toBe('rejected');expect(raw.creative.correction_complete).toBe(true);
 expect(JSON.parse(raw.creative.current_reply).changes).toHaveLength(7);
 await page.goto('/');
 await page.evaluate(wid=>localStorage.setItem('draftWorkspace',wid),workspace.id);
 await page.reload();await nav(page,'Создать');
 await workshopNav(page,'Проверка мира');
 await expect(page.getByText('Творческое развитие не завершено.',{exact:false})).toBeVisible();
 await expect(page.getByRole('button',{name:'Продолжить творческое развитие',exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Подтвердить мир и начать игру',exact:true})).toBeEnabled();
 const after=await(await request.get(url+'?author=true')).json();const result=await(await request.get(url+'/raw')).json();
 expect(after.review.status).toBe('completed');expect(after.version_id).toBe(before.version_id);
 expect(after.state).toEqual(before.state);
 expect(result.requests).toEqual(raw.requests);
 expect(result.creative.original_reply).toBe(raw.creative.original_reply);
 expect(result.creative.corrections).toHaveLength(0);
 expect(result.requests.filter((r:any)=>r.stage==='draft_world_creative')).toHaveLength(1);
 expect(result.requests.filter((r:any)=>r.stage==='draft_world_creative_repair')).toHaveLength(0);
 expect(result.requests.some((r:any)=>r.stage==='draft_world_validation')).toBe(true);
 expect(after.state.world.knowledge.know_ilya_love.status).toBe('unknown');
 expect(after.state.locations.some((r:any)=>r.id==='loc_veranda')).toBe(false);
 expect(after.state.locations.some((r:any)=>r.id==='loc_sonya_room')).toBe(false);
 expect(after.state.world.possessions.poss_sonya_tablet).toBeUndefined();
 await page.reload();await nav(page,'Создать');
 await page.getByRole('button',{name:'Подтвердить мир и начать игру',exact:true}).click();
 await confirmWorkshopStart(page);
 await expect(page.getByRole('button',{name:'Начать игру',exact:true})).toBeVisible();
 const selected=await page.evaluate(()=>JSON.parse(localStorage.getItem('selection')!));
 const author=await(await request.get(`/api/saves/${selected.save}/author-state`)).json();
 expect(author.snapshot.world_state.knowledge['ilya:fact_sonya_love'].status).toBe('unknown');
 expect(author.snapshot.world_state.knowledge['maxim:fact_maxim_sale'].status).toBe('known');
 expect(author.snapshot.world_state.locations.loc_sonya_room).toBeUndefined();
 expect(author.snapshot.world_state.possessions.poss_sonya_tablet).toBeUndefined();
 await page.reload();expect((await request.get(`/api/saves/${selected.save}`)).ok()).toBe(true);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});

def test_prompt_schema_does_not_remove_data_fields_named_like_annotations():
    schema=draft_initial.prompt_schema()
    assert 'title' in schema['properties']['campaign']['properties']
    assert 'description' in schema['properties']['campaign']['properties']
    world=schema['properties']['world']['properties']
    assert 'title' in world['roles']['additionalProperties']['properties']
    assert 'description' in world['conditions']['additionalProperties']['properties']
    def visit(value):
        if isinstance(value,dict):
            if value.get('type')=='object' and value.get('additionalProperties') is False:
                assert set(value.get('required',[]))<=set(value.get('properties',{}))
            for child in value.values():visit(child)
        if isinstance(value,list):
            for child in value:visit(child)
    visit(schema)


